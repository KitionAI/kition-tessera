//! Tessera Icons for kit engines.
//!
//! The engine draws tool cursors and on-canvas handles with the same icons as the editor around
//! it. Each icon is SVG path data on a 24 x 24 grid, drawn as round-capped strokes (1.5 units by
//! default); hand the paths to the engine's own path parser.

/// One icon: its name and its shapes as SVG path data. `paths` are stroked; `fills` (dots, solid
/// marks) are filled in the icon color and stroked.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Icon {
    pub name: &'static str,
    pub paths: &'static [&'static str],
    pub fills: &'static [&'static str],
    /// Accent areas (tool icons): filled with the skin's accent at [`ACCENT_OPACITY`], under the strokes.
    pub accents: &'static [&'static str],
}

/// How strongly accent areas are filled.
pub const ACCENT_OPACITY: f32 = 0.25;

/// The grid every icon is drawn on.
pub const GRID: f32 = 24.0;
/// The default stroke width, in grid units.
pub const STROKE: f32 = 1.5;

// Generated by `pnpm build:icons`, which `pnpm check:icons` compares byte for byte, so rustfmt leaves it alone.
#[rustfmt::skip]
mod generated;
pub use generated::*;

/// An icon by name (`layers`, `pen-line`).
pub fn icon(name: &str) -> Option<&'static Icon> {
    ICONS.binary_search_by(|icon| icon.name.cmp(name)).ok().map(|index| ICONS[index])
}

impl Icon {
    /// The icon as standalone SVG markup at `size` px in `color`.
    pub fn to_svg(&self, size: u32, color: &str) -> String {
        let color = color.replace('&', "&amp;").replace('"', "&quot;").replace('<', "&lt;");
        let mut out = format!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{size}\" height=\"{size}\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"{color}\" stroke-width=\"{STROKE}\" stroke-linecap=\"round\" stroke-linejoin=\"round\">"
        );
        for path in self.accents {
            out.push_str("<path d=\"");
            out.push_str(path);
            out.push_str("\" fill=\"");
            out.push_str(&color);
            out.push_str(&format!("\" fill-opacity=\"{ACCENT_OPACITY}\" stroke=\"none\"/>"));
        }
        for path in self.paths {
            out.push_str("<path d=\"");
            out.push_str(path);
            out.push_str("\"/>");
        }
        for path in self.fills {
            out.push_str("<path d=\"");
            out.push_str(path);
            out.push_str("\" fill=\"");
            out.push_str(&color);
            out.push_str("\"/>");
        }
        out.push_str("</svg>");
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn icons_are_sorted_and_unique() {
        assert!(ICONS.windows(2).all(|pair| pair[0].name < pair[1].name));
    }

    #[test]
    fn finds_icons_by_name() {
        assert_eq!(icon("layers").map(|icon| icon.name), Some("layers"));
        assert_eq!(icon("not-an-icon"), None);
        assert!(ICONS.iter().all(|icon| !icon.paths.is_empty() || !icon.fills.is_empty()));
    }

    #[test]
    fn writes_svg() {
        let svg = LAYERS.to_svg(16, "#5645d4");
        assert!(svg.starts_with("<svg ") && svg.ends_with("</svg>"));
        assert!(svg.contains("width=\"16\"") && svg.contains("stroke=\"#5645d4\""));
        assert_eq!(svg.matches("<path ").count(), LAYERS.paths.len());
    }
}
