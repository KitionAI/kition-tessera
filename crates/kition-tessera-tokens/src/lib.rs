//! Kition Tessera design tokens for kit engines.
//!
//! An engine that draws on the canvas (selection handles, guides, rulers) uses the same values as
//! the editor around it. The values are generated from `packages/tokens/tokens/*.tokens.json`;
//! the host's theme still wins at run time, so an engine takes its colors from the theme it is
//! given and falls back to these.

/// One token: its CSS variable, Paper value, the value under a dark color scheme when it
/// differs, and whether it is a Kit Harness Protocol theme token (hosts send those).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Token {
    pub name: &'static str,
    pub value: &'static str,
    pub dark: Option<&'static str>,
    pub khp: bool,
}

/// A skin's Kit UI protocol theme: its id, whether it is dark, and its theme tokens.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Skin {
    pub id: &'static str,
    pub dark: bool,
    pub tokens: &'static [(&'static str, &'static str)],
}

// Generated by `pnpm build:tokens`, which `pnpm check:tokens` compares byte for byte, so rustfmt leaves it alone.
#[rustfmt::skip]
mod generated;
pub use generated::*;

/// A token by CSS variable name (`--kit-primary`).
pub fn token(name: &str) -> Option<&'static Token> {
    TOKENS.iter().find(|token| token.name == name)
}

/// A skin by id (`paper`, `graphite`).
pub fn skin(id: &str) -> Option<&'static Skin> {
    SKINS.iter().find(|skin| skin.id == id)
}

impl Skin {
    /// The skin's value of a theme token.
    pub fn get(&self, name: &str) -> Option<&'static str> {
        self.tokens.iter().find(|(token, _)| *token == name).map(|(_, value)| *value)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn paper_is_kition() {
        let paper = skin("paper").expect("paper");
        assert!(!paper.dark);
        assert_eq!(paper.get("--kit-primary"), Some("#5645d4"));
        assert_eq!(paper.get("--kit-radius-control"), Some("8px"));
        assert_eq!(paper.get("--kit-radius-card"), Some("12px"));
        assert_eq!(KIT_PRIMARY, "#5645d4");
    }

    #[test]
    fn skins_carry_every_theme_token() {
        let khp = TOKENS.iter().filter(|token| token.khp).count();
        assert_eq!(khp, 15);
        for skin in SKINS {
            assert_eq!(skin.tokens.len(), khp, "{}", skin.id);
        }
        assert!(skin("graphite").expect("graphite").dark);
    }

    #[test]
    fn layout_tokens_are_not_sent_by_hosts() {
        assert!(!token("--kui-bar-height").expect("bar height").khp);
        assert_eq!(token("--kit-meter-bg").expect("meter").dark, Some("#000000"));
    }
}
