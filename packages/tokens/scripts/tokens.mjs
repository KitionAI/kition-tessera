/**
 * Reads Tessera's token files (DTCG structure, CSS values) and turns them into the CSS, TypeScript,
 * and Rust that `build.mjs` writes. Pure functions over parsed JSON, so the tests run them directly.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const EXT = 'ai.kition.tessera'

/** @typedef {{ name: string, group: string, key: string, type: string, value: string, description: string, khp: boolean, dark: string | null }} Token */
/** @typedef {{ id: string, colorScheme: 'light' | 'dark', description: string, overrides: Record<string, string> }} Skin */

/** Every token of a token document, in file order. Group names become the CSS prefix (`kit` → `--kit-*`). */
export function flatten(doc) {
  /** @type {Token[]} */
  const tokens = []
  for (const [group, entries] of Object.entries(doc)) {
    if (group.startsWith('$')) continue
    for (const [key, token] of Object.entries(entries)) {
      if (key.startsWith('$')) continue
      if (typeof token?.$value !== 'string') throw new Error(`${group}.${key}: $value must be a CSS string`)
      const ext = token.$extensions?.[EXT] ?? {}
      tokens.push({
        name: `--${group}-${key}`,
        group,
        key,
        type: token.$type ?? entries.$type ?? 'other',
        value: token.$value,
        description: token.$description ?? '',
        khp: ext.khp === true,
        dark: typeof ext.dark === 'string' ? ext.dark : null,
      })
    }
  }
  const seen = new Set()
  for (const token of tokens) {
    if (seen.has(token.name)) throw new Error(`${token.name} is defined twice`)
    seen.add(token.name)
  }
  return tokens
}

/** A skin file: its id and scheme, and the CSS variables it overrides. Overriding a token base does not define is an error. */
export function readSkin(doc, base) {
  const ext = doc.$extensions?.[EXT] ?? {}
  if (typeof ext.skin !== 'string' || !/^[a-z][a-z0-9-]*$/.test(ext.skin)) throw new Error('a skin needs a lowercase $extensions skin id')
  if (ext.colorScheme !== 'light' && ext.colorScheme !== 'dark') throw new Error(`${ext.skin}: colorScheme must be light or dark`)
  const known = new Set(base.map((token) => token.name))
  /** @type {Record<string, string>} */
  const overrides = {}
  for (const token of flatten(doc)) {
    if (!known.has(token.name)) throw new Error(`${ext.skin}: ${token.name} is not a base token`)
    overrides[token.name] = token.value
  }
  return /** @type {Skin} */ ({ id: ext.skin, colorScheme: ext.colorScheme, description: doc.$description ?? '', overrides })
}

/** The Kit UI protocol theme a host sends for a skin (`ui/initialize`, `ui/theme`): only the KHP tokens. */
export function skinTheme(skin, base) {
  /** @type {Record<string, string>} */
  const tokens = {}
  for (const token of base) if (token.khp) tokens[token.name] = skin.overrides[token.name] ?? token.value
  return { colorScheme: skin.colorScheme, tokens }
}

/** Reads `tokens/base.tokens.json` and every `tokens/skins/*.tokens.json`; Paper first, then by id. */
export function load(dir) {
  const base = flatten(JSON.parse(readFileSync(join(dir, 'base.tokens.json'), 'utf8')))
  const skins = readdirSync(join(dir, 'skins'))
    .filter((file) => file.endsWith('.tokens.json'))
    .map((file) => readSkin(JSON.parse(readFileSync(join(dir, 'skins', file), 'utf8')), base))
    .sort((a, b) => (a.id === 'paper' ? -1 : b.id === 'paper' ? 1 : a.id.localeCompare(b.id)))
  if (skins[0]?.id !== 'paper') throw new Error('the paper skin is missing')
  return { base, skins }
}

const BANNER = 'Generated by @kition/tessera-tokens from tokens/*.tokens.json. Do not edit; run `pnpm build:tokens`.'

/** `:root` with every token's Paper value, then `:root[data-color-scheme='dark']` with the tokens that change for dark. */
export function toCss(base) {
  const lines = [`/* ${BANNER} */`, ':root {']
  for (const token of base) lines.push(`  ${token.name}: ${token.value};`)
  lines.push('}')
  const dark = base.filter((token) => token.dark !== null)
  if (dark.length > 0) {
    lines.push('', ":root[data-color-scheme='dark'] {")
    for (const token of dark) lines.push(`  ${token.name}: ${token.dark};`)
    lines.push('}')
  }
  return lines.join('\n') + '\n'
}

/** The CSS variables a stylesheet's first `selector { … }` block declares, in order (comments ignored). */
export function declarations(css, selector) {
  const start = css.indexOf(`${selector} {`)
  if (start < 0) return null
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('\n}', start))
  /** @type {Record<string, string>} */
  const out = {}
  for (const match of body.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[match[1]] = match[2].trim()
  return out
}

const tsString = (value) => JSON.stringify(value)

export function toTs(base, skins) {
  const names = base.map((token) => tsString(token.name)).join(' | ')
  const khp = base.filter((token) => token.khp).map((token) => tsString(token.name))
  const out = [
    `// ${BANNER}`,
    '',
    '/** Every Tessera CSS variable. */',
    `export type TokenName = ${names}`,
    '',
    '/** A Kit Harness Protocol theme token (Kit UI protocol, section 4). */',
    `export type KhpTokenName = ${khp.join(' | ')}`,
    '',
    '/** One token: its CSS variable, DTCG type, Paper value, the value under a dark color scheme when it differs, and whether hosts send it. */',
    'export type Token = { name: TokenName; type: string; value: string; dark: string | null; khp: boolean; description: string }',
    '',
    '/** The Kit UI protocol theme for one skin. */',
    "export type SkinTheme = { colorScheme: 'light' | 'dark'; tokens: Record<KhpTokenName, string> }",
    '',
    'export const TOKENS: readonly Token[] = [',
    ...base.map(
      (token) =>
        `  { name: ${tsString(token.name)}, type: ${tsString(token.type)}, value: ${tsString(token.value)}, dark: ${token.dark === null ? 'null' : tsString(token.dark)}, khp: ${token.khp}, description: ${tsString(token.description)} },`,
    ),
    ']',
    '',
    `export const KHP_TOKENS: readonly KhpTokenName[] = [${khp.join(', ')}]`,
    '',
    `export type SkinId = ${skins.map((skin) => tsString(skin.id)).join(' | ')}`,
    '',
    '/** Every skin\'s theme, as a host sends it in `ui/initialize` and `ui/theme`. */',
    'export const SKINS: Readonly<Record<SkinId, SkinTheme>> = {',
  ]
  for (const skin of skins) {
    const theme = skinTheme(skin, base)
    out.push(`  ${skin.id}: {`, `    colorScheme: ${tsString(theme.colorScheme)},`, '    tokens: {')
    for (const [name, value] of Object.entries(theme.tokens)) out.push(`      ${tsString(name)}: ${tsString(value)},`)
    out.push('    },', '  },')
  }
  out.push('}', '')
  return out.join('\n')
}

const rustIdent = (name) => name.replace(/^--/, '').replace(/-/g, '_').toUpperCase()
const rustString = (value) => JSON.stringify(value)

export function toRust(base, skins) {
  const out = [`// ${BANNER}`, '', 'use crate::{Skin, Token};', '', '// Each token\'s Paper value, by CSS variable name (`--kit-surface` is `KIT_SURFACE`).']
  for (const token of base) {
    if (token.description) out.push(`/// ${token.description}`)
    out.push(`pub const ${rustIdent(token.name)}: &str = ${rustString(token.value)};`)
  }
  out.push('', '/// Every token: CSS variable, Paper value, dark value when it differs, and whether hosts send it.', 'pub const TOKENS: &[Token] = &[')
  for (const token of base) {
    out.push(`    Token { name: ${rustString(token.name)}, value: ${rustString(token.value)}, dark: ${token.dark === null ? 'None' : `Some(${rustString(token.dark)})`}, khp: ${token.khp} },`)
  }
  out.push('];', '', '/// Every skin\'s Kit UI protocol theme tokens.', 'pub const SKINS: &[Skin] = &[')
  for (const skin of skins) {
    const theme = skinTheme(skin, base)
    out.push(`    Skin {`, `        id: ${rustString(skin.id)},`, `        dark: ${theme.colorScheme === 'dark'},`, '        tokens: &[')
    for (const [name, value] of Object.entries(theme.tokens)) out.push(`            (${rustString(name)}, ${rustString(value)}),`)
    out.push('        ],', '    },')
  }
  out.push('];', '')
  return out.join('\n')
}
