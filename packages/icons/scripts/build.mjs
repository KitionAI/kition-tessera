#!/usr/bin/env node
/**
 * Builds Tessera Icons from `icons.json`: every icon as path strings in TypeScript
 * (`src/generated/`) and in the `tessera-icons` crate (`src/generated.rs`), React components, and
 * the list of kit icons in `kit/`. `--check` writes nothing and fails when a file is out of date.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toPaths } from './geometry.mjs'
import { lucideIndex } from './lucide.mjs'

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..')
const root = join(pkg, '..', '..')
const BANNER = 'Generated by @kition/tessera-icons from icons.json. Do not edit; run `pnpm build:icons`.'
const FAMILIES = new Set(['ui', 'tool'])

const manifest = JSON.parse(readFileSync(join(pkg, 'icons.json'), 'utf8'))
const lucide = await lucideIndex()
if (lucide.version !== manifest.lucide) throw new Error(`icons.json pins lucide ${manifest.lucide}, ${lucide.version} is installed`)

const pascal = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('')
const snake = (name) => name.replace(/-/g, '_').toUpperCase()

/** @type {{ name: string, family: string, paths: string[], fills: string[], accents: string[], lucide: string[] }[]} */
const icons = []
for (const [name, entry] of Object.entries(manifest.icons)) {
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(name)) throw new Error(`${name}: names are lowercase kebab-case and start with a letter`)
  if (!FAMILIES.has(entry.family)) throw new Error(`${name}: family must be ui or tool`)
  const [kind, ref] = String(entry.source).split(':')
  let shapes
  let lucideNames = []
  if (kind === 'lucide') {
    const nodes = lucide.nodes.get(ref)
    if (!nodes) throw new Error(`${name}: lucide ${lucide.version} has no ${ref}`)
    shapes = { ...toPaths(nodes), accents: [] }
    lucideNames = lucide.exportsOf.get(ref) ?? []
  } else if (kind === 'svg') {
    shapes = svgPaths(readFileSync(join(pkg, 'svg', ref), 'utf8'), name)
  } else {
    throw new Error(`${name}: source must be lucide:<name> or svg:<file>`)
  }
  icons.push({ name, family: entry.family, ...shapes, lucide: lucideNames })
}
icons.sort((a, b) => a.name.localeCompare(b.name))
for (const [label, ids] of [
  ['TypeScript', icons.map((icon) => pascal(icon.name))],
  ['Rust', icons.map((icon) => snake(icon.name))],
]) {
  if (new Set(ids).size !== ids.length) throw new Error(`two icons share a ${label} identifier`)
}

/**
 * A Tessera SVG drawing (24 × 24, `<path>` elements only) as paths, fills, and accents:
 * `fill="currentColor"` marks a filled mark, `data-accent="true"` an accent area (filled with the
 * skin's accent under the strokes, never stroked).
 */
function svgPaths(svg, name) {
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${name}: drawings use viewBox="0 0 24 24"`)
  if (/<(circle|rect|line|polyline|polygon|ellipse|g|use)\b/.test(svg)) throw new Error(`${name}: convert shapes to paths`)
  const paths = []
  const fills = []
  const accents = []
  for (const [element] of svg.matchAll(/<path\b[^>]*>/g)) {
    const d = /\sd="([^"]+)"/.exec(element)?.[1]
    if (!d) throw new Error(`${name}: a path without d`)
    ;(/\sdata-accent="true"/.test(element) ? accents : /\sfill="currentColor"/.test(element) ? fills : paths).push(d)
  }
  if (paths.length + fills.length === 0) throw new Error(`${name}: no paths`)
  return { paths, fills, accents }
}

const kitFiles = readdirSync(join(pkg, 'kit')).filter((file) => file.endsWith('.svg'))
const kits = kitFiles
  .filter((file) => !file.endsWith('-small.svg'))
  .map((file) => file.slice(0, -4))
  .sort()
for (const kit of kits) if (!kitFiles.includes(`${kit}-small.svg`)) throw new Error(`kit/${kit}-small.svg is missing`)

const js = (value) => JSON.stringify(value)

const iconsTs = [
  `// ${BANNER}`,
  '',
  "import type { IconData } from '../types.ts'",
  '',
  ...icons.map((icon) => `export const ${pascal(icon.name)}: IconData = { name: ${js(icon.name)}, family: ${js(icon.family)}, paths: ${js(icon.paths)}, fills: ${js(icon.fills)}, accents: ${js(icon.accents)} }`),
  '',
].join('\n')

const lucideMap = icons.flatMap((icon) => icon.lucide.map((alias) => [alias, icon.name])).sort(([a], [b]) => a.localeCompare(b))
const registryTs = [
  `// ${BANNER}`,
  '',
  "import type { IconData } from '../types.ts'",
  "import * as all from './icons.ts'",
  '',
  '/** Every icon, by name. Importing this pulls in the whole set; import single icons from the package root instead. */',
  `export const ICONS: Readonly<Record<string, IconData>> = Object.fromEntries(Object.values(all).map((icon) => [icon.name, icon]))`,
  '',
  `export const ICON_NAMES: readonly string[] = ${js(icons.map((icon) => icon.name))}`,
  '',
  '/** lucide-react export name (canonical or alias) to Tessera icon name, for moving code off lucide. */',
  'export const FROM_LUCIDE: Readonly<Record<string, string>> = {',
  ...lucideMap.map(([alias, name]) => `  ${alias}: ${js(name)},`),
  '}',
  '',
  '/** Kit app icons: full-color tiles in `@kition/tessera-icons/kit/<kit>.svg` and `<kit>-small.svg`. */',
  `export const KIT_ICONS: readonly string[] = ${js(kits)}`,
  '',
].join('\n')

const reactTs = [
  `// ${BANNER}`,
  '',
  "import { createIcon } from '../createIcon.ts'",
  "import * as data from './icons.ts'",
  '',
  // Pure, so bundlers drop the icons a page never uses.
  ...icons.map((icon) => `export const ${pascal(icon.name)}Icon = /* @__PURE__ */ createIcon(data.${pascal(icon.name)})`),
  '',
].join('\n')

const rust = [
  `// ${BANNER}`,
  '',
  'use crate::Icon;',
  '',
  ...icons.map((icon) => `pub const ${snake(icon.name)}: Icon = Icon { name: ${js(icon.name)}, paths: &[${icon.paths.map(js).join(', ')}], fills: &[${icon.fills.map(js).join(', ')}], accents: &[${icon.accents.map(js).join(', ')}] };`),
  '',
  '/// Every icon, sorted by name.',
  'pub static ICONS: &[&Icon] = &[',
  ...icons.map((icon) => `    &${snake(icon.name)},`),
  '];',
  '',
].join('\n')

const outputs = [
  [join(pkg, 'src', 'generated', 'icons.ts'), iconsTs],
  [join(pkg, 'src', 'generated', 'registry.ts'), registryTs],
  [join(pkg, 'src', 'generated', 'react.ts'), reactTs],
  [join(root, 'crates', 'tessera-icons', 'src', 'generated.rs'), rust],
]

const check = process.argv.includes('--check')
let stale = 0
for (const [file, text] of outputs) {
  let current = null
  try {
    current = readFileSync(file, 'utf8')
  } catch {}
  if (current === text) continue
  if (check) {
    console.error(`out of date: ${relative(root, file)}`)
    stale++
  } else {
    writeFileSync(file, text)
    console.log(`wrote ${relative(root, file)}`)
  }
}
if (stale > 0) {
  console.error('run `pnpm build:icons`')
  process.exit(1)
}
if (!check) console.log(`${icons.length} icons, ${kits.length} kit icons`)
